def get_current_language(request):
    """Detect language from session or user model (default: en)."""
    if not request:
        return "en"
    lang = request.session.get("django_language")
    if not lang and hasattr(request, "user") and request.user.is_authenticated:
        lang = getattr(request.user, "language", None)
    if lang not in ["en", "hi", "mr"]:
        lang = "en"
    return lang


def portal_language_context(request):
    """
    Context processor automatically injecting language tokens into all Django portal templates.
    """
    current_lang = get_current_language(request)
    t = PORTAL_TRANSLATIONS.get(current_lang, PORTAL_TRANSLATIONS["en"])

    return {
        "current_lang": current_lang,
        "t": t,
        "available_languages": [
            ("en", "English"),
            ("hi", "हिंदी"),
            ("mr", "मराठी"),
        ],
    }
